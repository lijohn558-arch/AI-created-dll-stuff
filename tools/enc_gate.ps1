# enc_gate.ps1 -- encoding gate: UTF-8 without BOM, pure LF (no CR), valid UTF-8.
# Covers the design docs (00/02/05) AND the hand-maintained shader/C++ sources.
# Rationale for the source pass: a CRLF shader slipped in once and the whole file
# showed up as changed in every diff, so CR bytes are now a hard FAIL everywhere.
# Exit 1 on any problem. Pure ASCII script.
$ErrorActionPreference = 'Stop'
$repo = 'C:\Users\joker\skyrim-vulkan'
$docs = Join-Path $repo 'docs'
$strict = New-Object System.Text.UTF8Encoding($false, $true)
$fail = $false

function Test-File([string]$path, [string]$label) {
    $b = [System.IO.File]::ReadAllBytes($path)
    $bom = ($b.Length -ge 3 -and $b[0] -eq 0xEF -and $b[1] -eq 0xBB -and $b[2] -eq 0xBF)
    $lf = 0; $cr = 0
    for ($i = 0; $i -lt $b.Length; $i++) {
        if ($b[$i] -eq 0x0A) { $lf++; if ($i -gt 0 -and $b[$i-1] -eq 0x0D) { $cr++ } }
    }
    $u8 = $true
    try { [void]$strict.GetString($b) } catch { $u8 = $false }
    $ok = (-not $bom) -and ($cr -eq 0) -and $u8
    if (-not $ok) { $script:fail = $true }
    Write-Output ("{0,-34} {1,7} B  LF={2,5} CRLF={3,4} BOM={4} utf8={5}  {6}" -f $label, $b.Length, $lf, $cr, $bom, $u8, $(if ($ok) { "OK" } else { "FAIL" }))
}

# ---- design docs (unchanged scope) ----
foreach ($pat in @('00-*.md', '02-*.md', '05-*.md')) {
    $hit = @(Get-ChildItem -LiteralPath $docs -Filter $pat)
    if ($hit.Count -ne 1) { Write-Output ("ERR " + $pat + " count=" + $hit.Count); $fail = $true; continue }
    Test-File $hit[0].FullName $hit[0].Name
}

# ---- hand-maintained sources: CR bytes are a hard FAIL here too ----
# NOTE: pocb_shaders.h is machine generated by tools/make_shaders.ps1 and is listed
# here only as SKIPPED (its line endings are whatever the generator emits; changing
# that generator is a separate decision, not something to sneak in here).
# Get-ChildItem -Path <dir> -Filter <pat> is non-recursive, so these two dirs are
# exactly "shaders" and "the TU dir", no extra filtering needed.
$dirs = @('shaders', '.')
foreach ($d in $dirs) {
    foreach ($pat in @('*.frag', '*.vert', '*.cpp', '*.h')) {
        $dir = Join-Path $repo ('src\poc-presenter\' + $d)
        if (-not (Test-Path -LiteralPath $dir)) { continue }
        foreach ($f in @(Get-ChildItem -LiteralPath $dir -Filter $pat -File)) {
            if ($f.Name -eq 'pocb_shaders.h') {
                Write-Output ("{0,-34} {1}" -f 'pocb_shaders.h', 'SKIPPED (generated by make_shaders.ps1)')
                continue
            }
            Test-File $f.FullName $f.Name
        }
    }
}

if ($fail) { Write-Output "ENC GATE FAIL"; exit 1 }
Write-Output "ENC GATE PASS"
exit 0